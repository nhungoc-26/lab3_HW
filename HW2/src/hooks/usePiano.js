
import { useCallback, useEffect, useRef, useState } from "react";
import { VoiceManager } from "../audio/VoiceManager";

const KEY_MAP = {
  KeyA: 60, // C4
  KeyW: 61, // C#4
  KeyS: 62, // D4
  KeyE: 63, // D#4
  KeyD: 64, // E4
  KeyF: 65, // F4
  KeyT: 66, // F#4
  KeyG: 67, // G4
  KeyY: 68, // G#4
  KeyH: 69, // A4
  KeyU: 70, // A#4
  KeyJ: 71, // B4
  KeyK: 72, // C5
};

// Abortable delay for asynchronous sequence playback.
function wait(ms, signal) {
  return new Promise((resolve, reject) => {
    if (signal.aborted) {
      reject(new DOMException("Playback cancelled", "AbortError"));
      return;
    }

    const timer = window.setTimeout(() => {
      signal.removeEventListener("abort", handleAbort);
      resolve();
    }, Math.max(0, ms));

    function handleAbort() {
      window.clearTimeout(timer);
      reject(new DOMException("Playback cancelled", "AbortError"));
    }

    signal.addEventListener("abort", handleAbort, { once: true });
  });
}

export function usePiano() {
  const voiceManagerRef = useRef(null);

  const [pressedNotes, setPressedNotes] = useState(() => new Set());
  const [sampleStatus, setSampleStatus] = useState("idle");
  const [recordedSequence, setRecordedSequence] = useState([]);
  const [isPlayingSequence, setIsPlayingSequence] = useState(false);

  // Recording and playback references.
  const sequenceRef = useRef([]);
  const activeRecordingsRef = useRef(new Map());
  const lastRecordedAtRef = useRef(null);
  const playbackControllerRef = useRef(null);
  const isReplayingRef = useRef(false);

  if (voiceManagerRef.current === null) {
    voiceManagerRef.current = new VoiceManager(8);
  }

  // Finalize one recorded note.
  const finishRecording = useCallback((midi, endTime) => {
    const record = activeRecordingsRef.current.get(midi);

    if (!record) return;

    record.durationMs = Math.max(0, endTime - record.startedAt);
    delete record.startedAt;

    activeRecordingsRef.current.delete(midi);
    setRecordedSequence([...sequenceRef.current]);
  }, []);

  // Play a note and record its starting time.
  const noteOn = useCallback((midi) => {
    const manager = voiceManagerRef.current;

    // Map.has() replaces the old Array.some() check.
    if (manager.voices.has(midi)) return;

    const freqHz = manager.getFrequency(midi);
    manager.noteOn(midi, freqHz);

    setPressedNotes((previous) => {
      if (previous.has(midi)) return previous;

      const next = new Set(previous);

      if (next.size >= 8) {
        const oldestNote = next.values().next().value;
        next.delete(oldestNote);
      }

      next.add(midi);
      return next;
    });

    // Do not record notes generated by sequence replay.
    if (!isReplayingRef.current) {
      const now = performance.now();
      const deltaMs =
        lastRecordedAtRef.current === null
          ? 0
          : Math.max(0, now - lastRecordedAtRef.current);

      const record = {
        midi,
        freqHz,
        durationMs: 0,
        deltaMs,
        startedAt: now,
      };

      sequenceRef.current.push(record);
      activeRecordingsRef.current.set(midi, record);
      lastRecordedAtRef.current = now;

      setRecordedSequence([...sequenceRef.current]);
    }
  }, []);

  // Release a note and save its duration.
  const noteOff = useCallback((midi) => {
    voiceManagerRef.current.noteOff(midi);

    finishRecording(midi, performance.now());

    setPressedNotes((previous) => {
      if (!previous.has(midi)) return previous;

      const next = new Set(previous);
      next.delete(midi);
      return next;
    });
  }, [finishRecording]);

  // Stop all notes and finish any incomplete recordings.
  const stopAll = useCallback(() => {
    const now = performance.now();

    for (const midi of activeRecordingsRef.current.keys()) {
      finishRecording(midi, now);
    }

    voiceManagerRef.current.stopAll();
    setPressedNotes(new Set());
  }, [finishRecording]);

  // Test the FIFO AudioTaskQueue.
  const testAudioQueue = useCallback(async () => {
    setSampleStatus("loading");

    try {
      const audioBuffer =
        await voiceManagerRef.current.loadAudio("/audio/test.wav");

      voiceManagerRef.current.playBuffer(audioBuffer);
      setSampleStatus("success");
    } catch (error) {
      if (error.name !== "AbortError") {
        console.error("Audio queue error:", error);
        setSampleStatus("error");
      }
    }
  }, []);

  // Cancel the current melody replay.
  const stopSequence = useCallback(() => {
    playbackControllerRef.current?.abort();
    playbackControllerRef.current = null;

    isReplayingRef.current = false;
    voiceManagerRef.current.stopAll();

    setPressedNotes(new Set());
    setIsPlayingSequence(false);
  }, []);

  // Replay recorded notes at 0.5x, 1x, or 2x speed.
  const replaySequence = useCallback(async (speed = 1) => {
    if (![0.5, 1, 2].includes(speed)) return;

    const sequence = sequenceRef.current.filter(
      (record) => record.durationMs > 0
    );

    if (sequence.length === 0) return;

    // Cancel any previous replay before starting another one.
    playbackControllerRef.current?.abort();
    voiceManagerRef.current.stopAll();

    const controller = new AbortController();
    playbackControllerRef.current = controller;

    isReplayingRef.current = true;
    setIsPlayingSequence(true);
    setPressedNotes(new Set());

    const releaseTasks = [];

    try {
      for (const record of sequence) {
        await wait(record.deltaMs / speed, controller.signal);

        if (controller.signal.aborted) break;

        voiceManagerRef.current.noteOn(record.midi, record.freqHz);

        setPressedNotes((previous) => {
          const next = new Set(previous);

          if (next.size >= 8) {
            next.delete(next.values().next().value);
          }

          next.add(record.midi);
          return next;
        });

        // Schedule note release without blocking the next FIFO note.
        const releaseTask = wait(
          record.durationMs / speed,
          controller.signal
        ).then(() => {
          voiceManagerRef.current.noteOff(record.midi);

          setPressedNotes((previous) => {
            const next = new Set(previous);
            next.delete(record.midi);
            return next;
          });
        });

        releaseTasks.push(releaseTask);
      }

      await Promise.all(releaseTasks);
    } catch (error) {
      if (error.name !== "AbortError") {
        console.error("Sequence playback error:", error);
      }
    } finally {
      if (playbackControllerRef.current === controller) {
        voiceManagerRef.current.stopAll();
        playbackControllerRef.current = null;
        isReplayingRef.current = false;

        setPressedNotes(new Set());
        setIsPlayingSequence(false);
      }
    }
  }, []);

  // Clear the recorded melody.
  const clearRecording = useCallback(() => {
    stopSequence();

    sequenceRef.current = [];
    activeRecordingsRef.current.clear();
    lastRecordedAtRef.current = null;

    setRecordedSequence([]);
  }, [stopSequence]);

  // Computer keyboard controls.
  useEffect(() => {
    const heldKeys = new Set();

    const handleKeyDown = (event) => {
      const target = event.target;

      if (
        target instanceof HTMLElement &&
        (target.isContentEditable ||
          ["INPUT", "TEXTAREA", "SELECT"].includes(target.tagName))
      ) {
        return;
      }

      const midi = KEY_MAP[event.code];

      if (midi === undefined || event.repeat) return;

      event.preventDefault();

      if (heldKeys.has(event.code)) return;

      heldKeys.add(event.code);
      noteOn(midi);
    };

    const handleKeyUp = (event) => {
      const midi = KEY_MAP[event.code];

      if (midi === undefined || !heldKeys.has(event.code)) return;

      heldKeys.delete(event.code);
      noteOff(midi);
    };

    const handleBlur = () => {
      heldKeys.clear();
      stopAll();
    };

    window.addEventListener("keydown", handleKeyDown);
    window.addEventListener("keyup", handleKeyUp);
    window.addEventListener("blur", handleBlur);

    return () => {
      window.removeEventListener("keydown", handleKeyDown);
      window.removeEventListener("keyup", handleKeyUp);
      window.removeEventListener("blur", handleBlur);

      playbackControllerRef.current?.abort();
      voiceManagerRef.current?.dispose();
    };
  }, [noteOn, noteOff, stopAll]);

  return {
    pressedNotes,
    noteOn,
    noteOff,
    stopAll,
    testAudioQueue,
    sampleStatus,
    recordedSequence,
    isPlayingSequence,
    replaySequence,
    stopSequence,
    clearRecording,
  };
}
